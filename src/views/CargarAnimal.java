    private void botoncargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoncargarActionPerformed
                                           
    try {
        Especie especie = (Especie) nombrebox.getSelectedItem();
        Sector sector = (Sector) sectorcombo.getSelectedItem();
        TipoAlimentacion alimentacion = (TipoAlimentacion) alimentacionbox.getSelectedItem();
        int edad = Integer.parseInt(edadtxt.getText());
        double peso = Double.parseDouble(pesotxt.getText());

        Mamifero animal = null;

        if (alimentacion == TipoAlimentacion.CARNIVORO) {
            animal = new Carnivoro(edad, peso, especie, sector, null);
        } else {
            animal = new Herbivoro(edad, peso, especie, sector, 0.0, null);
        }

        Persistencia.agregarAnimal(animal); 
        System.out.println("Animal cargado correctamente.");

        ListarAnimalesView vista = new ListarAnimalesView();
        vista.setVisible(true);
        System.out.println("Vista de lista abierta.");

        this.dispose();
        
    } catch (Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error al cargar el animal: " + ex.getMessage());
    }

    }//GEN-LAST:event_botoncargarActionPerformed

