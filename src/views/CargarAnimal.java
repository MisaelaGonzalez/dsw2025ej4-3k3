     private void cargarAlimentacion() {
        for (TipoAlimentacion tipo : TipoAlimentacion.values()) {
            alimentacionbox.addItem(tipo);
        }
    }

     private void cargarSectores() {
        for (Sector s : Persistencia.getSectores()) {
            sectorcombo.addItem(s);
        }
    }

   private void cargarPaises() {
    comboPais.removeAllItems(); // Limpiar el combo antes de cargar

    for (Pais p : Persistencia.getPaises()) {
        comboPais.addItem(p);
    }
}
